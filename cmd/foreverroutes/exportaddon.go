// export-addon writes the route files as Lua data for the in-game addon: every route replayed with the dataset, each
// step with what to do (take, do an objective, hand in, grind), where (world yards on the continent), the level by
// then, and how to get there when it is not on foot (a deathskip with its place to die and graveyard, the hearthstone).
func cmdExportAddon(args []string) error {
	fs := newFlags("export-addon")
	path := fs.String("data", "data/routes-data.json.gz", "dataset")
	dir := fs.String("routes", "data/routes", "route files")
	profiles := fs.String("profiles", "data/profiles", "kill profiles (<class>.json)")
	fallbackFile := fs.String("fallbacks", "", "ordinary pinned RXP fallback catalog; default beside dataset")
	out := fs.String("out", "", "Lua file to write (the addon's Data/Routes.lua)")
	stale := fs.Bool("stale-ok", false, "interim release before a recompute: a route with events the data no longer allows is exported without them")
	personal := fs.Bool("personal", false, "only the routes of -routes, added to the shipped ones (the addon's Data/Personal.lua: a route ForeverCore planned with the character's own kill profile)")
	forever := fs.String("forever", "", "ForeverDB's full quest list: its chain rules are applied as the blocks command does (for routes planned with them)")
	fs.Parse(args)
	if *forever != "" {
		list, err := blocks.Load(*forever)
		if err != nil {
			return err
		}
		datasetEdit = func(d *dataset.Dataset) { list.Apply(d) }
		defer func() { datasetEdit = nil }()
	}
	if *fallbackFile == "" {
		*fallbackFile = filepath.Join(filepath.Dir(*path), "fallbacks", "rxp.json.gz")
	}
	if *out == "" {
		return fmt.Errorf("export-addon needs -out")
	}
	var cat *fallback.Catalog
	var err error
	if !*personal {
		if cat, err = fallback.Load(*fallbackFile); err != nil {
			return fmt.Errorf("RXP fallbacks: %w", err)
		}
	}
	files, err := filepath.Glob(filepath.Join(*dir, "*.json"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	// a route continued past 20 (routes-ext beside the routes, extend -stages) takes the place of its base route
	for i, f := range files {
		if *personal {
			break
		}
		if e := filepath.Join(filepath.Dir(filepath.Clean(*dir)), "routes-ext", filepath.Base(f)); fileExists(e) {
			files[i] = e
		}
	}
	// test stretches (routes-tests beside the routes: a route from a character's state over a few levels, /fr test)
	if !*personal {
		tests, _ := filepath.Glob(filepath.Join(filepath.Dir(filepath.Clean(*dir)), "routes-tests", "*.json"))
		sort.Strings(tests)
		files = append(files, tests...)
	}
	var b strings.Builder
	b.WriteString("-- Generated by foreverroutes export-addon from data/routes (github.com/Battlefeld/ForeverRoutes); do not edit.\n")
	b.WriteString("-- Routes whose basis is \"guide\" are adapted from the RestedXP Forever guides (github.com/RestedXP/RXPGuides,\n")
	b.WriteString("-- CC BY-NC-SA 4.0) and shared under the same licence; the rest are ForeverRoutes' own.\n")
	b.WriteString("-- A step: op a(ccept) w(ork) t(urnin) g(rind) d(ungeon run; ii instance map id, qi quests taken inside); q quest, n name; o objective (1-based, route order), k kind, c count,\n")
	b.WriteString("-- tg target; m continent, x y world yards (x north, y west); l level reached by then; v d(eathskip) or h(earth)\n")
	b.WriteString("-- with dm dx dy the place to die and gy the graveyard; bn bm bx by the innkeeper the hearthstone is bound at, bu when a later hearthstone trip uses it.\n")
	if *personal {
		// beside the shipped routes, not in their place: the addon takes it only with the data it was planned on
		// (dataVersion), else the shipped route counts until ForeverCore plans the personal one anew
		b.WriteString("-- Personal: planned by ForeverCore with this character's own kill profile (its items and talents); taken instead of the shipped route while the data are the same.\n")
		b.WriteString("ForeverRoutesData = ForeverRoutesData or {}\nForeverRoutesData.personal = ForeverRoutesData.personal or {}\n")
	} else {
		b.WriteString("ForeverRoutesData = ForeverRoutesData or {}\nForeverRoutesData.routes = {}\nForeverRoutesData.tests = {}\n")
	}
	var ds *dataset.Dataset
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var r struct {
			RouteModel
			Character route.Character    `json:"character"`
			Target    int                `json:"target"`
			Winner    string             `json:"winner"`
			Hours     map[string]float64 `json:"hours"`
			Events    []route.GuideEvent `json:"events"`
			Options   []route.ClassCost  `json:"classQuests"`
			Wand      float64            `json:"wandDetour"`
			Start     *route.Live        `json:"start"`    // a personal route planned from the character's state
			TestZone  string             `json:"testZone"` // a test stretch of one zone: ForeverRoutesData.tests[key][zone] (/fr test)
		}
		if err := json.Unmarshal(raw, &r); err != nil || len(r.Events) == 0 {
			return fmt.Errorf("%s: malformed or empty route", f)
		}
		prof := filepath.Join(*profiles, strings.ToLower(r.Character.Class)+".json")
		if !fileExists(prof) {
			prof = ""
		}
		w, err := withModel(r.RouteModel, func() (*route.World, error) {
			return loadWorld(*path, r.Character.Race, r.Character.Class, r.Character.Faction, prof, hasDungeons(r.Events))
		})
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		if err := r.RouteModel.apply(w); err != nil {
			return err
		}
		w.SetWandDetour(r.Wand)
		ds = w.Data
		key := strings.TrimSuffix(filepath.Base(f), ".json")
		if r.TestZone != "" {
			key = r.Character.RouteKey()
		}
		var res *route.GuideResult
		if r.Start != nil {
			var s *route.State
			if s, _, err = w.StateFrom(*r.Start); err == nil {
				res, err = w.FollowGuideFromState(s, r.Events, r.Target)
			}
		} else {
			res, err = w.FollowGuide(r.Events, r.Target)
		}
		if err != nil {
			// a route the dataset no longer carries: left out (the addon says it has no route), not the whole export
			fmt.Fprintf(os.Stderr, "%s: left out: %v\n", key, err)
			continue
		}
		if (res.Level < r.Target || len(res.Skipped) > 0) && r.TestZone != "" && r.Start != nil {
			// a test stretch the data no longer carries whole: left out, the shipped routes go out
			fmt.Fprintf(os.Stderr, "%s / %s: test stretch left out: %d skipped events\n", key, r.TestZone, len(res.Missed))
			continue
		}
		if res.Level < r.Target || len(res.Skipped) > 0 {
			if *personal || !*stale && !outsideFocus(key, readFocus("data/focus.txt")) {
				return fmt.Errorf("%s: incomplete route or skipped events; regenerate routes", f)
			}
			fmt.Fprintf(os.Stderr, "%s: stale route exported without %d skipped events\n", key, len(res.Missed))
		}
		mark, table := "", "routes"
		if *personal {
			// its own revision: the addon starts it over from the first step not done yet instead of keeping the
			// shipped route's place
			version, err := dataVersion(*path)
			if err != nil {
				return err
			}
			mark, table = fmt.Sprintf("personal = true, dataVersion = %s, revision = %s, ", luaStr(version), luaStr(fmt.Sprintf("%s-personal-%.0f", version, res.Seconds))), "personal"
		}
		slot := "ForeverRoutesData." + table + "[" + luaStr(key) + "]"
		if r.TestZone != "" {
			fmt.Fprintf(&b, "ForeverRoutesData.tests[%s] = ForeverRoutesData.tests[%s] or {}\n", luaStr(key), luaStr(key))
			slot = "ForeverRoutesData.tests[" + luaStr(key) + "][" + luaStr(r.TestZone) + "]"
			mark += "test = " + luaStr(r.TestZone) + ", "
			if r.Start != nil {
				mark += fmt.Sprintf("start = %d, ", r.Start.Level)
			}
		}
		fmt.Fprintf(&b, "%s = {race = %s, class = %s, faction = %s, target = %d, hours = %.1f, basis = %s, %ss = {\n",
			slot, luaStr(r.Character.Race), luaStr(r.Character.Class), luaStr(r.Character.Faction), r.Target, res.Seconds/3600, luaStr(r.Winner), mark)
		for _, st := range res.Steps {
			b.WriteString(" {")
			writeStep(&b, w, res, st)
			b.WriteString("},\n")
		}
		b.WriteString("}")
		writeOptions(&b, w, res, r.Options, r.Target)
		b.WriteString("}\n")
		fmt.Fprintf(os.Stderr, "%s: %d steps, %.1f h\n", key, len(res.Steps), res.Seconds/3600)
	}
	if *personal {
		if ds == nil {
			return fmt.Errorf("no route in %s", *dir)
		}
		return os.WriteFile(*out, []byte(b.String()), 0o644)
	}
	if ds != nil {
		fmt.Fprintf(&b, "ForeverRoutesData.build = %s\n", luaStr(ds.Build))
		// the dataset itself (its build is the game's): a personal route counts only with the data it was planned on
		version, err := dataVersion(*path)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "ForeverRoutesData.dataVersion = %s\n", luaStr(version))
		// every quest's full XP and level: the XP bar shows what the quests in the log give (the game's own value
		// first, this one when the client has none)
		// the dungeons a player can choose for an own route (up to level 45), in the order of their levels: key, name,
		// the levels the game lets in, the level a route runs it from, and the side when only one has it
		b.WriteString("ForeverRoutesData.dungeons = {\n")
		list := append([]dataset.Dungeon{}, ds.Dungeons...)
		sort.SliceStable(list, func(i, j int) bool { return list[i].Min < list[j].Min })
		for _, d := range list {
			if route.DungeonFrom(d.Key, d.Min, d.Max) > 45 {
				continue
			}
			fmt.Fprintf(&b, " {key = %s, n = %s, min = %d, max = %d, from = %d, f = %s},\n", luaStr(d.Key), luaStr(d.Name), d.Min, d.Max, route.DungeonFrom(d.Key, d.Min, d.Max), luaStr(d.Faction))
		}
		b.WriteString("}\n")
		b.WriteString("ForeverRoutesData.questXP = {")
		for i, q := range ds.Quests {
			if q.XP > 0 {
				fmt.Fprintf(&b, "[%d]={%d,%d},", q.ID, q.XP, q.Level)
			}
			if i%40 == 39 {
				b.WriteString("\n")
			}
		}
		b.WriteString("}\n")
	}
	// The quest chains that lead to a dungeon's quests, per side: the window names the first open step of each before
	// the run ("Leaders of the Fang: first The Forgotten Pools").
	b.WriteString("ForeverRoutesData.dungeonChains = {}\n")
	for _, side := range []struct{ faction, race string }{{"H", "Orc"}, {"A", "Human"}} {
		w, err := loadWorld(*path, side.race, "Warrior", side.faction, "", true)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "ForeverRoutesData.dungeonChains[%s] = {", luaStr(side.faction))
		for _, d := range w.Dungeons {
			var chains []string
			for _, q := range d.Quests {
				steps := w.ChainBefore(q)
				if len(steps) == 0 {
					continue
				}
				var parts []string
				for _, st := range steps {
					parts = append(parts, fmt.Sprintf("{q=%d,n=%s}", st.ID, luaStr(st.Name)))
				}
				chains = append(chains, fmt.Sprintf("{q=%d,n=%s,steps={%s}}", q.ID, luaStr(q.Name), strings.Join(parts, ",")))
			}
			if len(chains) > 0 {
				fmt.Fprintf(&b, "[%s]={%s},", luaStr(d.Name), strings.Join(chains, ","))
			}
		}
		b.WriteString("}\n")
	}
	// The RestedXP guides as plain step lists: the addon follows one instead of the optimized route when the player
	// chooses it (/fr guide rxp), live planning off.
	b.WriteString("ForeverRoutesData.guides = {}\n")
	for _, g := range cat.Routes {
		if len(g.Events) == 0 {
			continue
		}
		prof := filepath.Join(*profiles, strings.ToLower(g.Character.Class)+".json")
		if !fileExists(prof) {
			prof = ""
		}
		w, err := loadWorld(*path, g.Character.Race, g.Character.Class, g.Character.Faction, prof, false)
		if err != nil {
			return fmt.Errorf("RXP %s: %w", g.Key, err)
		}
		res, err := w.FollowGuide(g.Events, cmp.Or(g.Target, 20))
		if err != nil {
			fmt.Fprintf(os.Stderr, "RXP %s: left out: %v\n", g.Key, err)
			continue
		}
		fmt.Fprintf(&b, "ForeverRoutesData.guides[%s] = {race = %s, class = %s, faction = %s, target = %d, hours = %.1f, basis = \"rxp\", s = {\n",
			luaStr(g.Key), luaStr(g.Character.Race), luaStr(g.Character.Class), luaStr(g.Character.Faction), cmp.Or(g.Target, 20), res.Seconds/3600)
		for _, st := range res.Steps {
			b.WriteString(" {")
			writeStep(&b, w, res, st)
			b.WriteString("},\n")
		}
		b.WriteString("}}\n")
		fmt.Fprintf(os.Stderr, "RXP %s: %d steps, %.1f h\n", g.Key, len(res.Steps), res.Seconds/3600)
	}
	writeFallbackCatalog(&b, cat)
	return os.WriteFile(*out, []byte(b.String()), 0o644)
}

func writeFallbackCatalog(b *strings.Builder, c *fallback.Catalog) {
	fmt.Fprintf(b, "ForeverRoutesData.rxpRevision = %s\nForeverRoutesData.rxpLicense = %s\nForeverRoutesData.rxpChapters = {}\nForeverRoutesData.fallbacks = {}\n", luaStr(c.Revision), luaStr(c.License))
	var names []string
	for name := range c.Chapters {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		ch := c.Chapters[name]
		fmt.Fprintf(b, "ForeverRoutesData.rxpChapters[%s] = {file=%s, line=%d, body=%s}\n", luaStr(name), luaStr(ch.File), ch.Line, luaStr(ch.Body))
	}
	for _, r := range c.Routes {
		var chapters []string
		for _, name := range r.Chapters {
			chapters = append(chapters, luaStr(name))
		}
		fmt.Fprintf(b, "ForeverRoutesData.fallbacks[%s] = {kind=\"rxp-source\", race=%s, class=%s, faction=%s, target=20, chapters={%s}}\n", luaStr(r.Key), luaStr(r.Character.Race), luaStr(r.Character.Class), luaStr(r.Character.Faction), strings.Join(chapters, ","))
	}
	b.WriteString(`
-- Original chapter bodies retain RXP conditions, instructions and #next references.
-- The UI consumes these as RXP guides; they are independent of simulated optimized steps.
function ForeverRoutesData.SelectRoute(race, class, faction, dungeons, forceFallback)
  if race == "Scourge" then race = "Undead" end
  if race == "Skyborne" then
    if faction == "Alliance" then faction = "A" elseif faction == "Horde" then faction = "H" end
    if faction ~= "A" and faction ~= "H" then return nil, "missing faction" end
    race = race .. "-" .. faction
  end
  local base = string.lower(race .. "-" .. class)
  local key = base .. (dungeons and "-dungeons" or "")
  local best = ForeverRoutesData.routes[key]
  if not forceFallback and best and best.s and #best.s > 0 then return best, "optimized" end
  return ForeverRoutesData.fallbacks[base], "rxp-fallback"
end
`)
}

// writeStep writes a step's fields: what to do, where, the level by then, how to get there.
func writeStep(b *strings.Builder, w *route.World, res *route.GuideResult, st route.Step) {
	defer func() {
		if st.Zone != "" {
			fmt.Fprintf(b, ", z = %s", luaStr(st.Zone)) // the zone: "Gebietswechsel: weiter nach <z>"
		}
	}()
	q := w.ByID[st.Quest]
	switch st.Op {
	case "accept", "turnin":
		fmt.Fprintf(b, "op = %s, q = %d", luaStr(st.Op[:1]), st.Quest)
		if q != nil {
			fmt.Fprintf(b, ", n = %s", luaStr(q.Name))
		}
	case "work":
		fmt.Fprintf(b, "op = \"w\", q = %d", st.Quest)
		if q != nil && st.Obj < len(q.Objectives) {
			o := q.Objectives[st.Obj]
			fmt.Fprintf(b, ", n = %s, o = %d, k = %s, c = %d", luaStr(q.Name), st.Obj+1, luaStr(o.Kind), o.Count)
		}
		if tg := targetName(w, st.Action); tg != "" {
			fmt.Fprintf(b, ", tg = %s", luaStr(tg))
		}
	case "grind":
		fmt.Fprintf(b, "op = \"g\", c = %d", st.Kills)
		if n := w.NPC[st.NPC]; n != nil {
			fmt.Fprintf(b, ", tg = %s", luaStr(n.Name))
		}
	case "sleep":
		fmt.Fprintf(b, "op = \"sleep\", n = %s, it = 211527, stacks = %d, seconds = %.0f", luaStr(st.Name), st.Stacks, w.Opt.SleepingBag.PlacementSeconds+float64(st.Stacks)*w.Opt.SleepingBag.StackSeconds)
	case "prof":
		// trainers: Skinning, Cooking, Leatherworking (the Camp Tent at Leatherworking 20, cl the level the camps start)
		fmt.Fprintf(b, "op = \"p\", cl = %d", route.CampLevel)
	case "wand":
		// a capital's Enchanting trainer and supplier: the Novice's Practice Wand and the Lesser Magic Wand (it)
		fmt.Fprintf(b, "op = \"z\", it = %d, cl = %d", route.LesserWandItem, route.CampLevel)
	case "dungeon":
		fmt.Fprintf(b, "op = \"d\", n = %s", luaStr(strings.TrimSuffix(st.Name, " (dungeon run)")))
		for _, d := range w.Dungeons {
			if d.Key == st.Dungeon {
				fmt.Fprintf(b, ", ii = %d", d.Instance) // the instance's map id: the run is done in this dungeon only
			}
		}
		// quests taken inside that the route counts on: handed in later or inside
		var inside []string
		seen := map[string]bool{}
		for _, q := range w.StartedInside(st.Dungeon) {
			// a quest that gives no XP (the Sparklematic 5200 in Gnomeregan: a box, no XP) is not worth taking, and
			// a name is listed once (several quests of one name)
			if q.XP <= 0 || seen[q.Name] {
				continue
			}
			used := q.EndInside
			for _, later := range res.Steps {
				used = used || (later.Op == "turnin" && later.Quest == q.ID)
			}
			if used {
				seen[q.Name] = true
				inside = append(inside, luaStr(q.Name))
			}
		}
		if len(inside) > 0 {
			fmt.Fprintf(b, ", qi = {%s}", strings.Join(inside, ", "))
		}
	default:
		fmt.Fprintf(b, "op = %s", luaStr(st.Op))
	}
	fmt.Fprintf(b, ", m = %d, x = %.1f, y = %.1f, l = %d", st.At.Map, st.At.X, st.At.Y, st.Level)
	switch {
	case strings.HasPrefix(st.Via, "deathskip"):
		b.WriteString(`, v = "d"`)
		fmt.Fprintf(b, ", gy = %s", luaStr(strings.TrimPrefix(st.Via, "deathskip: ")))
		if st.ViaAt != nil {
			fmt.Fprintf(b, ", dm = %d, dx = %.1f, dy = %.1f", st.ViaAt.Map, st.ViaAt.X, st.ViaAt.Y)
		}
	case st.Via == "hearth":
		b.WriteString(`, v = "h"`)
	case st.Via == "teleport":
		b.WriteString(`, v = "t"`)
	}
	if st.StartBy != nil {
		// an item starts the quest: sk the creature to kill for it (sl its level, se elite), si the item
		fmt.Fprintf(b, ", sk = %s, sl = %d, si = %d", luaStr(st.StartBy.Name), st.StartBy.Level, st.StartBy.Item)
		if st.StartBy.Elite {
			b.WriteString(", se = true")
		}
	}
	if st.Bind != nil {
		// the hearthstone is bound here: bn the innkeeper, bm bx by where, bu a later hearthstone trip comes back to it
		fmt.Fprintf(b, ", bn = %s, bm = %d, bx = %.1f, by = %.1f", luaStr(st.Bind.Name), st.Bind.At.Map, st.Bind.At.X, st.Bind.At.Y)
		if st.BindUsed {
			b.WriteString(", bu = true")
		}
	}
}

// writeOptions writes the route's options (o): each option the addon can switch on, with its steps (from the route
// with it) and for each the step of the route it comes after (af, 0 before the first). Off, the route is as it is; on,
// its steps go in after theirs, and the route's grind steps are done earlier by themselves (a grind step is done at
// its level).
func writeOptions(b *strings.Builder, w *route.World, res *route.GuideResult, opts []route.ClassCost, target int) {
	key := func(st route.Step) string {
		switch st.Op {
		case "accept", "turnin", "work":
			return fmt.Sprintf("%s:%d:%d", st.Op, st.Quest, st.Obj)
		case "dungeon":
			return "dungeon:" + st.Dungeon
		}
		return ""
	}
	base := map[string]int{}
	for i, st := range res.Steps {
		if k := key(st); k != "" {
			if _, seen := base[k]; !seen {
				base[k] = i + 1
			}
		}
	}
	first := true
	for _, c := range opts {
		if c.InRoute || !c.Possible || c.Tier == "required" || len(c.Events) == 0 {
			continue
		}
		with, err := w.FollowGuide(c.Events, target)
		if err != nil {
			continue
		}
		mine := map[int]bool{}
		for _, q := range c.Quests {
			mine[q] = true
		}
		var steps []string
		af := 0
		for _, st := range with.Steps {
			k := key(st)
			if i, in := base[k]; in {
				af = i
				continue
			}
			if !mine[st.Quest] || k == "" {
				continue // the route with it differs elsewhere too: only the option's own steps go in
			}
			var s strings.Builder
			fmt.Fprintf(&s, " {af = %d, ", af)
			writeStep(&s, w, with, st)
			s.WriteString("},\n")
			steps = append(steps, s.String())
		}
		if len(steps) == 0 {
			continue
		}
		if first {
			b.WriteString(", o = {\n")
			first = false
		}
		name := c.Reward
		if name == "" {
			name = c.Name
		}
		note := ""
		if n, ok := route.OptionNotes[c.Quest]; ok {
			note = ", nt = " + luaStr(n)
		}
		fmt.Fprintf(b, "{id = %d, n = %s, tier = %s, min = %.0f, l = %d%s, s = {\n%s}},\n", c.Quest, luaStr(name), luaStr(c.Tier), c.Minutes, c.Level, note, strings.Join(steps, ""))
	}
	if !first {
		b.WriteString("}")
	}
}

// targetName is who or what a work step is done at: the creature, the object, else nothing (a place).
func targetName(w *route.World, a route.Action) string {
	if n := w.NPC[a.NPC]; n != nil {
		return n.Name
	}
	if o := w.Objects[a.Object]; o != nil {
		return o.Name
	}
	return ""
}

// luaStr quotes a string for Lua 5.1: backslash, quote and control characters escaped, other bytes (UTF-8) kept.
func luaStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '\\' || c == '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString(`\n`)
		case c < 0x20:
			fmt.Fprintf(&b, "\\%03d", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// readFocus: the focus (route keys with an optional scenario, comma separated) from FR_ROSTER_FOCUS or the focus
// file; empty: all routes.
func readFocus(file string) string {
	if focus := strings.TrimSpace(os.Getenv("FR_ROSTER_FOCUS")); focus != "" {
		return focus
	}
	b, err := os.ReadFile(file)
	if err != nil {
		return ""
	}
	var keys []string
	for _, line := range strings.Split(string(b), "\n") {
		if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "#") {
			keys = append(keys, line)
		}
	}
	return strings.Join(keys, ",")
}

// outsideFocus: the route file key (orc-shaman, orc-shaman-dungeons) is not one the focus keeps current. Those
// routes may lag a data fix: they ship without the events the data no longer allows.
func outsideFocus(key, focus string) bool {
	if focus == "" {
		return false
	}
	for _, k := range strings.Split(focus, ",") {
		base, scenario, _ := strings.Cut(strings.TrimSpace(k), ":")
		if key == base+"-dungeons" && scenario != "solo" || key == base && scenario != "dungeons" {
			return false
		}
	}
	return true
}

// dataVersion names the dataset file: the start of its SHA-256 (the dataset's build field is the game's build and
// stays the same across data updates).
func dataVersion(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:6]), nil
}
